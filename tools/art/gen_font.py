def book_glyphs() -> dict[str, list[str]]:
    glyphs = {}
    for char, rows in GLYPHS.items():
        glyphs[char] = rows + ["." * len(rows[0])] * (BOOK_HEIGHT - HEIGHT)
    glyphs.update(BOOK_EXTRA)
    glyphs.update(LOWER)
    return glyphs


TOP = 3
BOTTOM = 2
ACCENTS = {"acute": "́", "grave": "̀", "circ": "̂", "tilde": "̃"}
PT_LETTERS = {"A": "acute grave circ tilde", "E": "acute circ", "I": "acute", "O": "acute circ tilde", "U": "acute"}


def _ink_middle(rows: list[str]) -> float:
    cols = [i for row in rows for i, ch in enumerate(row) if ch == "#"]
    return (min(cols) + max(cols)) / 2.0


def _accent_pixels(kind: str, m: float) -> list[tuple[int, int]]:
    lo, hi = int(m), int(m + 0.5)
    if kind == "acute":
        return [(hi if lo != hi else lo + 1, 0), (lo, 1)]
    if kind == "grave":
        return [(lo if lo != hi else lo - 1, 0), (hi, 1)]
    if kind == "circ":
        return [(lo, 0), (hi, 0), (lo - 1, 1), (hi + 1, 1)]
    start = lo - 2 if lo == hi else lo - 1
    pattern = [".##.#", "#..#."] if lo == hi else [".#.#", "#.#."]
    return [(start + i, j) for j, row in enumerate(pattern) for i, ch in enumerate(row) if ch == "#"]


def _canvas(rows: list[str], height: int) -> list[list[str]]:
    width = len(rows[0])
    blank = ["."] * width
    return [list(blank) for _ in range(TOP)] + [list(r) for r in rows] + [list(blank) for _ in range(BOTTOM)] \
        if len(rows) == height else []


def _with_marks(rows: list[str], height: int, accent_row: int, kind: str = "", cedilla: bool = False) -> list[str]:
    canvas = _canvas(rows, height)
    if not kind and not cedilla:
        return ["".join(r) for r in canvas]
    m = _ink_middle(rows)
    width = len(rows[0])
    if kind:
        for col, j in _accent_pixels(kind, m):
            assert 0 <= col < width, (kind, rows)
            canvas[TOP + accent_row + j][col] = "#"
    if cedilla:
        col = int(m + 0.5)
        canvas[TOP + HEIGHT][col] = "#"
        canvas[TOP + HEIGHT + 1][col - 1] = "#"
        canvas[TOP + HEIGHT + 1][col] = "#"
    return ["".join(r) for r in canvas]


def tall(glyphs: dict[str, list[str]], height: int, lower: dict[str, list[str]] | None = None) -> dict[str, list[str]]:
    out = {char: _with_marks(rows, height, 0) for char, rows in glyphs.items()}
    for base, kinds in PT_LETTERS.items():
        for kind in kinds.split():
            char = unicodedata.normalize("NFC", base + ACCENTS[kind])
            out[char] = _with_marks(glyphs[base], height, -TOP, kind)
            if lower:
                small = base.lower()
                rows = list(lower[small])
                if small == "i":
                    rows[0] = "." * len(rows[0])
                out[unicodedata.normalize("NFC", small + ACCENTS[kind])] = _with_marks(rows, height, -1, kind)
    out["Ç"] = _with_marks(glyphs["C"], height, 0, cedilla=True)
    if lower:
        out["ç"] = _with_marks(lower["c"], height, 0, cedilla=True)
    return out


def build(glyphs: dict[str, list[str]], height: int, ascent: int, name: str) -> None:
    full = TOP + height + BOTTOM
    width = sum(len(rows[0]) + 1 for rows in glyphs.values())
    sheet = Image.new("RGBA", (width, full), (0, 0, 0, 0))
    px = sheet.load()
    meta = {"height": height, "ascent": ascent, "top": TOP, "bottom": BOTTOM, "glyphs": {}}
    x = 0
    for char, rows in glyphs.items():
        assert len(rows) == full and len({len(r) for r in rows}) == 1, char
        for j, row in enumerate(rows):
            for i, ch in enumerate(row):
                if ch == "#":
                    px[x + i, j] = (255, 255, 255, 255)
        meta["glyphs"][char] = [x, len(rows[0])]
        x += len(rows[0]) + 1
    save(sheet, "fonts", name + ".png")
    save_json(meta, "fonts", name + ".json")
    print("fonte %s: ok (%d caracteres)" % (name, len(glyphs)))


def main() -> None:
    build(tall(GLYPHS, HEIGHT), HEIGHT, HEIGHT, "serif")
    book = book_glyphs()
    build(tall(book, BOOK_HEIGHT, LOWER), BOOK_HEIGHT, BOOK_ASCENT, "serif_book")


if __name__ == "__main__":
    main()
